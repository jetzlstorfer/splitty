export type MessageKey = keyof typeof german;
export type Parameters = Record<string, string | number>;
export const localeFor = (language: Language) => language === "de" ? "de-AT" : "en-IE";

export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(german, value);
}

export function translate(language: Language, key: MessageKey, values: Parameters = {}): string {
  const template = language === "de" ? german[key] : key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    if (!(name in values)) throw new Error(`Missing translation parameter: ${name}`);
    return String(values[name]);
  });
}

export function localizeMessage(message: string, language: Language): string {
  if (!message) return "";
  if (isMessageKey(message)) return translate(language, message);
  const row = /^Row (\d+): (.+)$/s.exec(message);
  if (row) return translate(language, "Row {row}: {message}", { row: row[1], message: localizeMessage(row[2], language) });
  if (message.startsWith("CSV could not be read:")) return translate(language, "CSV could not be read. Check the file format and column count.");
  if (message.startsWith("Local storage failed:")) return translate(language, "Local storage failed. Check browser permissions and available storage.");
  if (message.startsWith("Offline setup failed:")) return translate(language, "Offline setup failed. Reload the app while online and try again.");
  if (/fetch|network/i.test(message)) return translate(language, "Network request failed. Your changes remain on this device.");
  if (/timeout|timed out|aborted/i.test(message)) return translate(language, "The request timed out. Your changes remain on this device.");
  return translate(language, "An unexpected error occurred. Your saved entries remain on this device.");
}
